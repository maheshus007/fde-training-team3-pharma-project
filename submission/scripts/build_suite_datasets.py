def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    written = []
    for s in SUITES:
        doc = {
            "suite_id": s["suite_id"],
            "name": s["slug"],
            "filename": f"{s['suite_id']}_{s['slug']}.json",
            "package_suite": s["package_suite"],
            "title": s["title"],
            "version": "1.0",
            "gate": s["gate"],
            "graders": s["graders"],
            "source": "evaluation/EVALUATION_PLAN.md required suites",
            "cases": s["cases"],
        }
        path = OUT / doc["filename"]
        path.write_text(json.dumps(doc, indent=2) + "\n", encoding="utf-8")
        written.append(path.name)
    print("wrote", len(written), "suite datasets:")
    for name in written:
        print("-", name)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
